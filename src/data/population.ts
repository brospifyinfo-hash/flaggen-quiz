/** Deutsch formatierte Einwohnerzahl, z. B. „83,5 Mio.“ */
export function formatPopulation(value: number): string {
  if (value >= 1_000_000) {
    const millions = value / 1_000_000
    return `${millions.toLocaleString('de-DE', { maximumFractionDigits: millions < 10 ? 1 : 0 })} Mio.`
  }
  return `${value.toLocaleString('de-DE')}`
}
